// Chaque rangée devient des rectangles (pixels voisins fusionnés)
export const PIXEL = {};
for (const [k, rows] of Object.entries(G)) {
  let d = '';
  rows.forEach((r, y) => {
    for (const m of r.slice(0, 12).matchAll(/#+/g)) d += `M${m.index * 2} ${y * 2}h${m[0].length * 2}v2h-${m[0].length * 2}z`;
  });
  PIXEL[k] = d;
}
